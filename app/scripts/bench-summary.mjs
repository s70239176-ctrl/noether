// Summarises deployments/bench/runs.jsonl into deployments/bench/BENCH.md.
//
//   node app/scripts/bench-summary.mjs
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../../", import.meta.url);
const rows = readFileSync(new URL("deployments/bench/runs.jsonl", root), "utf8").trim().split("\n").map((l) => JSON.parse(l));
const attacks = rows.filter((r) => r.kind === "attack");
const honest = rows.filter((r) => r.kind === "honest");
const errors = rows.filter((r) => r.kind === "error");

const X = { base: "https://sepolia.basescan.org/tx/", unichain: "https://sepolia.uniscan.xyz/tx/", lasna: "https://lasna.reactscan.net/tx/" };
const link = (chain, h) => (h ? `[${h.slice(0, 8)}…](${X[chain]}${h})` : "–");
const REASONS = ["NONE", "UNBACKED_MINT", "MINT_REPLAY", "MINT_MISMATCH", "UNBACKED_RELEASE", "RELEASE_REPLAY", "RELEASE_MISMATCH", "NEURAL_ESCALATION"];

function pct(xs, p) {
  const v = xs.filter((x) => x !== null && x !== undefined).sort((a, b) => a - b);
  if (!v.length) return null;
  return v[Math.min(v.length - 1, Math.ceil((p / 100) * v.length) - 1)];
}
const stat = (xs) => {
  const v = xs.filter((x) => x !== null && x !== undefined);
  return { n: v.length, p50: pct(v, 50), p95: pct(v, 95), max: v.length ? Math.max(...v) : null };
};
const s = (x, unit = " s") => (x === null || x === undefined ? "–" : `${x >= 0 && unit === " s" ? "+" : ""}${x}${unit}`);

const complete = attacks.filter((a) => a.baseS !== null && a.uniS !== null);
const rowsStat = [
  ["Noether decides (Lasna `ConservationBroken`)", attacks.map((a) => a.decisionS)],
  ["Base Sepolia route frozen", attacks.map((a) => a.baseS)],
  ["Unichain Sepolia route frozen", attacks.map((a) => a.uniS)],
  ["**Both routes frozen**", attacks.map((a) => a.bothS)],
  ["Cover sales closed", attacks.map((a) => (a.coverTs ? a.coverTs - a.originTs : null))],
  ["Attacker quarantined", attacks.map((a) => (a.quarantineTs ? a.quarantineTs - a.originTs : null))],
];
const obs = stat(attacks.map((a) => a.observerS));
const copyRejected = attacks.filter((a) => a.copycat === "rejected").length;
const copyTried = attacks.filter((a) => a.copycat !== "skipped").length;
const cb = attacks.map((a) => a.callbacks);
const reasons = {};
for (const a of attacks) reasons[REASONS[a.reason] ?? "none"] = (reasons[REASONS[a.reason] ?? "none"] || 0) + 1;
const falseFreezes = honest.filter((h) => h.falseFreeze).length;
const suspects = honest.reduce((n, h) => n + h.suspectsRaised, 0);
const cleared = honest.reduce((n, h) => n + h.suspectsCleared, 0);
const first = rows[0]?.at, last = rows[rows.length - 1]?.at;

const o = [];
const p = (x = "") => o.push(x);
p("# Noether live benchmark");
p();
p(`Real testnets: Base Sepolia, Unichain Sepolia and Reactive Lasna, on Noether's Hyperlane warp route. Runs from ${first} to ${last}. Generated by \`app/scripts/bench.mjs\` (raw rows: [runs.jsonl](runs.jsonl)) and summarised by \`app/scripts/bench-summary.mjs\`.`);
p();
p("Each cycle sends 1 or 2 honest 100 dUSD transfers, then a **forged mint** through Hyperlane's real Unichain Mailbox with the route's compromised relayer key, then a **copycat** forged message, then a governance resolve back to NORMAL.");
p();
p("## Results");
p();
p(`| | Runs | Result |`);
p(`|---|---|---|`);
p(`| Forged mints | ${attacks.length} | **${complete.length}/${attacks.length}** froze both routes |`);
p(`| Callbacks per reaction | ${cb.length} | ${[...new Set(cb)].sort().join(", ")} (Base guard, cover, Unichain guard, quarantine) |`);
p(`| Copycat forged messages | ${copyTried} | **${copyRejected}/${copyTried}** rejected by the frozen ISM |`);
p(`| Honest transfers | ${honest.length} | **${falseFreezes} false freezes**; ${honest.filter((h) => h.matched).length}/${honest.length} matched by message id; ${suspects} suspects raised (${cleared} auto-cleared) |`);
p(`| Detection path | ${attacks.length} | ${Object.entries(reasons).map(([k, v]) => `${k} ${v}`).join(", ")} |`);
if (errors.length) p(`| Cycles that errored (RPC or relay) | ${errors.length} | listed below, not counted as freezes |`);
p();
if (Object.keys(reasons).length === 1 && reasons.NEURAL_ESCALATION) {
  p("Every forgery in this run took the neural fast path (p ≥ 0.95), so none waited for the grace window. The grace path (a quiet forgery frozen after the window, and an honest out-of-order delivery auto-cleared) is covered by `test_ForgedMintThatLooksHonestFreezesAfterGrace` and `test_OutOfOrderMintIsHeldThenAutoCleared`.");
  p();
}
if (errors.length) {
  p("Errored cycles failed in a public RPC call or in the resolve step, never in detection. Each attack's data was recorded before its resolve. One errored cycle's honest transfers were rejected with `ISM verification failed` because the previous resolve had timed out, so the route was still frozen: the freeze holding, not a false positive.");
  p();
}
p("## Latency from the forged mint (block timestamps)");
p();
p("Each value is a destination block's timestamp minus the forged mint's Unichain block timestamp. Every chain keeps its own clock at 1 s granularity, so Lasna can read −1 s.");
p();
p("| Step | n | p50 | p95 | max |");
p("|---|---|---|---|---|");
for (const [label, xs] of rowsStat) {
  const t = stat(xs);
  p(`| ${label} | ${t.n} | ${s(t.p50)} | ${s(t.p95)} | ${s(t.max)} |`);
}
p();
p(`**Observer check:** wall-clock time from the forged receipt until both guards read \`frozen()\` through public RPCs (500 ms poll, includes RPC lag). p50 ${obs.p50} s, p95 ${obs.p95} s, max ${obs.max} s (n = ${obs.n}).`);
p();
p("## Every attack");
p();
p("| # | Forged mint (Unichain) | Noether reacts (Lasna) | Base frozen | Unichain frozen | Callbacks | Copycat |");
p("|---|---|---|---|---|---|---|");
attacks.forEach((a, i) => {
  p(`| ${i + 1} | ${link("unichain", a.forgedTx)} ${Number(a.amount).toLocaleString("en-US")} | ${link("lasna", a.lasnaTx)} ${s(a.decisionS)} | ${link("base", a.baseFrozenTx)} ${s(a.baseS)} | ${link("unichain", a.uniFrozenTx)} ${s(a.uniS)} | ${a.callbacks} | ${a.copycat} |`);
});
p();
p("## Every honest transfer");
p();
p("| # | Dispatch (Base) | Delivery (Unichain) | Matched | Suspects | False freeze |");
p("|---|---|---|---|---|---|");
honest.forEach((h, i) => {
  p(`| ${i + 1} | ${link("base", h.dispatchTx)} | ${link("unichain", h.deliveryTx)} | ${h.matched ? "yes" : "no"} | ${h.suspectsRaised} | ${h.falseFreeze ? "**yes**" : "no"} |`);
});
if (errors.length) {
  p();
  p("## Errored cycles");
  p();
  for (const e of errors) p(`- cycle ${e.cycle} at ${e.at}: ${e.error.replace(/\s+/g, " ")}`);
}
writeFileSync(new URL("deployments/bench/BENCH.md", root), o.join("\n") + "\n");
console.log(o.slice(0, 40).join("\n"));
